/**
 * Renders a styled label for a dropdown menu.
 *
 * The label includes a data-slot attribute for automation and supports an optional inset spacing
 * to align with items that have leading indicators. Additional props are forwarded to the underlying Radix primitive.
 *
 * @param className - Additional CSS classes to apply to the label
 * @param inset - When `true`, applies left inset padding to align the label with inset items
 * @returns A React element representing the dropdown menu label
 */
function DropdownMenuLabel({
  className,
  inset,
  ...props
}: React.ComponentProps<typeof DropdownMenuPrimitive.Label> & {
  inset?: boolean
}) {
  return (
    <DropdownMenuPrimitive.Label
      data-slot="dropdown-menu-label"
      data-inset={inset}
      className={cn(
        "px-2 py-1.5 text-sm font-medium data-[inset]:pl-8",
        className
      )}
      {...props}
    />
  )
}

