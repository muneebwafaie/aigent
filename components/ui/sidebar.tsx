/**
 * Renders a styled sidebar menu button, optionally wrapped with a tooltip visible only when the sidebar is collapsed on desktop.
 *
 * @param asChild - If `true`, renders `Slot.Root` instead of a native `button`, allowing the caller to supply the element.
 * @param isActive - Marks the button as active which influences its styling.
 * @param variant - Visual variant used for the button's styling.
 * @param size - Size variant used for the button's styling.
 * @param tooltip - If a string, used as tooltip content; if an object, treated as `TooltipContent` props. When provided, the button is wrapped in a `Tooltip` whose content is hidden unless the sidebar `state` is `"collapsed"` and the viewport is not mobile.
 * @param className - Additional class names applied to the button element.
 * @returns The rendered button element (or the supplied child element when `asChild` is `true`); when `tooltip` is provided, returns the button wrapped in a `Tooltip`.
 */
function SidebarMenuButton({
  asChild = false,
  isActive = false,
  variant = "default",
  size = "default",
  tooltip,
  className,
  ...props
}: React.ComponentProps<"button"> & {
  asChild?: boolean
  isActive?: boolean
  tooltip?: string | React.ComponentProps<typeof TooltipContent>
} & VariantProps<typeof sidebarMenuButtonVariants>) {
  const Comp = asChild ? Slot.Root : "button"
  const { isMobile, state } = useSidebar()

  const button = (
    <Comp
      data-slot="sidebar-menu-button"
      data-sidebar="menu-button"
      data-size={size}
      data-active={isActive}
      className={cn(sidebarMenuButtonVariants({ variant, size }), className)}
      {...props}
    />
  )

  if (!tooltip) {
    return button
  }

  if (typeof tooltip === "string") {
    tooltip = {
      children: tooltip,
    }
  }

  return (
    <Tooltip>
      <TooltipTrigger asChild>{button}</TooltipTrigger>
      <TooltipContent
        side="right"
        align="center"
        hidden={state !== "collapsed" || isMobile}
        {...tooltip}
      />
    </Tooltip>
  )
}

